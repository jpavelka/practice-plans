#!/usr/bin/env python3
"""Extract the field-diagram image from each drill PDF.

These PDFs (generated by "easy Sports Organizer") embed the diagram as a single
DCTDecode (JPEG) XObject on page 1. We carve those bytes straight out of the PDF,
so this has ZERO third-party dependencies.

Usage:
    python3 tools/extract_diagrams.py <pdf-dir> <out-dir> [--map ids.json]
                                      [--manifest manifest.json]

--map takes {"<pdf filename>": "<drill-id>"} and names each output <drill-id>.jpg.
Without it, output names are slugged from the PDF *filename*, which is not the
drill id -- attachment filenames arrive mangled. Always pass --map in the pipeline;
the bare form is for one-off inspection.

Exit code is non-zero if any PDF yielded no diagram, so a pipeline can catch it.

FALLBACK NOT IMPLEMENTED: if a future PDF stores its diagram as vector art or a
FlateDecode bitmap, this script reports it as a miss rather than guessing. The
agreed fallback (render page 1 wholesale to PNG) needs a real PDF renderer
-- pymupdf or pdfjs-dist -- which is not installed here. Add it when a PDF
actually fails; every one of the 7 sample PDFs succeeds on the primary path.
"""
import json
import re
import sys
from pathlib import Path

SOI, EOI = b"\xff\xd8\xff", b"\xff\xd9"


def _int_length(raw: bytes, dict_blob: bytes) -> int | None:
    """/Length may be a direct int or an indirect '12 0 R' reference."""
    m = re.search(rb"/Length\s+(\d+)(?!\s+\d+\s+R)", dict_blob)
    if m:
        return int(m.group(1))
    m = re.search(rb"/Length\s+(\d+)\s+(\d+)\s+R", dict_blob)
    if not m:
        return None
    num, gen = m.group(1).decode(), m.group(2).decode()
    ref = re.search(
        rf"(?<![0-9]){num}\s+{gen}\s+obj\s*(\d+)".encode(), raw
    )
    return int(ref.group(1)) if ref else None


def extract_jpegs(pdf: Path) -> list[dict]:
    """Return every DCTDecode image in the file, largest first."""
    raw = pdf.read_bytes()
    if b"/Encrypt" in raw:
        raise ValueError(f"{pdf.name}: encrypted PDF, cannot extract")

    found = []
    for m in re.finditer(rb"/Subtype\s*/Image", raw):
        # the object dictionary surrounding this marker
        start = raw.rfind(b"obj", 0, m.start())
        stream = raw.find(b"stream", m.end())
        if start == -1 or stream == -1:
            continue
        blob = raw[start:stream]
        if b"/DCTDecode" not in blob:
            continue  # not a JPEG; vector or Flate bitmap

        # payload begins after the EOL that follows the `stream` keyword
        p = stream + len(b"stream")
        if raw[p : p + 2] == b"\r\n":
            p += 2
        elif raw[p : p + 1] in (b"\n", b"\r"):
            p += 1

        length = _int_length(raw, blob)
        data = raw[p : p + length] if length else raw[p : raw.find(b"endstream", p)]

        # trim to true JPEG boundaries; tolerates a wrong /Length
        s = data.find(SOI)
        e = data.rfind(EOI)
        if s == -1 or e == -1:
            continue
        data = data[s : e + 2]

        w = re.search(rb"/Width\s+(\d+)", blob)
        h = re.search(rb"/Height\s+(\d+)", blob)
        found.append({
            "bytes": data,
            "width": int(w.group(1)) if w else None,
            "height": int(h.group(1)) if h else None,
        })

    found.sort(key=lambda i: (i["width"] or 0) * (i["height"] or 0), reverse=True)
    return found


def slug(name: str) -> str:
    """Filename -> id. Repairs the punctuation mangling seen in mail attachments
    (',' -> '^J', '&' -> '^0'). IDs still come from the PDF *title* in the real
    pipeline; this is only for standalone runs."""
    s = name.replace("^J", ",").replace("^0", "&").lower()
    s = re.sub(r"[^a-z0-9]+", "-", s)
    return re.sub(r"-+", "-", s).strip("-")


def main(argv: list[str]) -> int:
    if len(argv) < 3:
        print(__doc__)
        return 2
    pdf_dir, out_dir = Path(argv[1]), Path(argv[2])
    manifest_path = None
    if "--manifest" in argv:
        manifest_path = Path(argv[argv.index("--manifest") + 1])

    id_map: dict[str, str] = {}
    if "--map" in argv:
        id_map = json.loads(Path(argv[argv.index("--map") + 1]).read_text())

    out_dir.mkdir(parents=True, exist_ok=True)
    pdfs = sorted(pdf_dir.glob("*.pdf"))
    if not pdfs:
        print(f"no PDFs in {pdf_dir}", file=sys.stderr)
        return 1

    manifest, misses = {}, []
    for pdf in pdfs:
        try:
            images = extract_jpegs(pdf)
        except ValueError as exc:
            print(f"  !! {exc}", file=sys.stderr)
            misses.append(pdf.name)
            continue
        if not images:
            print(f"  !! {pdf.name}: no DCTDecode image -- needs render fallback",
                  file=sys.stderr)
            misses.append(pdf.name)
            continue

        best = images[0]
        stem = id_map.get(pdf.name)
        if id_map and stem is None:
            print(f"  !! {pdf.name}: not in --map, falling back to filename slug",
                  file=sys.stderr)
            misses.append(pdf.name)
        # .jpg, not .png: the source bytes are already JPEG. Re-encoding to PNG
        # would inflate a photographic image several-fold for zero quality gain.
        dest = out_dir / f"{stem or slug(pdf.stem)}.jpg"
        dest.write_bytes(best["bytes"])
        manifest[pdf.name] = {
            "path": str(dest),
            "width": best["width"],
            "height": best["height"],
            "bytes": len(best["bytes"]),
            "otherImagesInPdf": len(images) - 1,
        }
        print(f"  ok {dest.name}  {best['width']}x{best['height']}  "
              f"{len(best['bytes']) // 1024} KB"
              + (f"  (+{len(images) - 1} smaller ignored)" if len(images) > 1 else ""))

    if manifest_path:
        manifest_path.write_text(json.dumps(manifest, indent=2) + "\n")
        print(f"manifest -> {manifest_path}")

    print(f"\n{len(manifest)}/{len(pdfs)} diagrams extracted")
    if misses:
        print(f"MISSES ({len(misses)}): " + ", ".join(misses), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
